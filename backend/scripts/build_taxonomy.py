"""Build taxonomy/skills.yaml from O*NET Hot Technologies plus taxonomy/aliases.yaml.

    uv run python -m scripts.build_taxonomy            # rebuild from the committed O*NET extract
    uv run python -m scripts.build_taxonomy --download # refresh onet_hot_tech.txt first

skills.yaml is a YAML list of {name, aliases, case_sensitive}. Matching rules live in
app/extract/taxonomy.py.
"""

import argparse
import csv
import io
from pathlib import Path

import httpx
import yaml

TAXONOMY = Path(__file__).resolve().parents[2] / "taxonomy"
ONET_URL = "https://www.onetcenter.org/dl_files/database/db_30_2_text/Technology%20Skills.txt"


def download() -> None:
    response = httpx.get(ONET_URL, timeout=60, follow_redirects=True)
    response.raise_for_status()
    rows = csv.DictReader(io.StringIO(response.text), delimiter="\t")
    hot = sorted({(r["Example"], r["Commodity Title"]) for r in rows if r["Hot Technology"] == "Y"})
    lines = ["Example\tCommodity Title"] + [f"{name}\t{title}" for name, title in hot]
    (TAXONOMY / "onet_hot_tech.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build() -> list[dict]:
    rules = yaml.safe_load((TAXONOMY / "aliases.yaml").read_text(encoding="utf-8"))
    include, drop, rename = set(rules["include_categories"]), set(rules["drop"]), rules["rename"]
    case_sensitive = set(rules["case_sensitive"])
    skills: dict[str, list[str]] = {}
    with (TAXONOMY / "onet_hot_tech.txt").open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            name = row["Example"]
            if row["Commodity Title"] not in include or name in drop:
                continue
            canonical = rename.get(name, name)
            aliases = skills.setdefault(canonical, [])
            if canonical != name:
                aliases.append(name)
    for canonical, extra in rules["skills"].items():
        skills.setdefault(canonical, []).extend(extra)
    owners: dict[str, str] = {}
    for name, aliases in skills.items():
        for term in {name, *aliases}:
            key = term if term in case_sensitive else term.lower()
            if owners.setdefault(key, name) != name:
                raise ValueError(f"{term!r} belongs to both {owners[key]!r} and {name!r}")
    return [
        {
            "name": name,
            "aliases": sorted(set(aliases) - {name}),
            "case_sensitive": sorted(t for t in [name, *aliases] if t in case_sensitive),
        }
        for name, aliases in sorted(skills.items(), key=lambda item: item[0].lower())
    ]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--download", action="store_true")
    if parser.parse_args().download:
        download()
    entries = build()
    header = "# Generated by backend/scripts/build_taxonomy.py from O*NET + aliases.yaml.\n"
    body = yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=100)
    (TAXONOMY / "skills.yaml").write_text(header + body, encoding="utf-8")
    print(f"{len(entries)} skills")


if __name__ == "__main__":
    main()
